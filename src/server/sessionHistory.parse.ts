// Parser transcript agent (Claude `~/.claude/projects/*/*.jsonl`, Codex `~/.codex/sessions/**`)
// menjadi ringkasan sesi untuk panel Agent History. Murni (tanpa fs, tanpa sqlite) supaya grammar
// per CLI teruji langsung, dan supaya pemindai bisa MENYAMBUNG state lama dengan baris baru saja
// (indeks inkremental: hanya byte yang ditambahkan sejak scan terakhir yang di-parse).
//
// Ditiru dari Orca `src/main/ai-vault/scanners/claude/session-scanner-primary-parsers.ts` dan
// `scanners/codex/session-scanner-codex-parser.ts`: judul = prompt user PERTAMA yang asli, turn
// suntikan harness (`isMeta`, tag `<system-reminder>` dkk., `shared/harness-injected-user-turns.ts`)
// dilewati. Tambahan webterm: catatan `[webterm]`/`[nodeterm]` yang diketik ke PTY oleh link-note
// juga bukan prompt pengguna.

export type HistoryAgent = 'claude' | 'codex'

/** State parse satu file transcript. Dipersist apa adanya di indeks supaya scan berikutnya bisa
 *  melanjutkan dari `parsedBytes` tanpa membaca ulang file dari awal. */
export interface SessionParseState {
  agent: HistoryAgent
  id: string
  cwd: string | null
  title: string | null
  startedAt: number | null
  endedAt: number | null
  messageCount: number
}

/** Panjang judul tersimpan; baris daftar hanya butuh pratinjau, bukan prompt utuh. */
export const TITLE_MAX = 160

// Tag/prefix yang terbukti disuntikkan harness sebagai turn user (salinan daftar Orca
// `KNOWN_HARNESS_TAG_NAMES`/`HARNESS_INJECTED_TURN_PREFIXES` + bootstrap codex).
const HARNESS_TAGS = new Set([
  'agent-message', 'bash-input', 'bash-stderr', 'bash-stdout', 'command-args', 'command-message',
  'command-name', 'cross-session-message', 'fork-boilerplate', 'local-command-caveat',
  'local-command-stderr', 'local-command-stdout', 'mcp-polling-update', 'mcp-resource-update',
  'system-reminder', 'task-notification', 'teammate-message', 'user-memory-input',
  'user-prompt-submit-hook', 'environment_context', 'user_instructions', 'instructions', 'turn_aborted',
])
const HARNESS_PREFIXES = [
  '<channel source=', '[request interrupted', 'a message arrived from ',
  'another claude session sent a message', 'no response requested.',
  'caveat: the messages below were generated by the user while running local commands',
  'this session is being continued from a previous conversation', '# agents.md instructions',
  '[webterm]', '[nodeterm]',
]
const LEADING_TAG = /^<([a-z][a-z0-9_-]*)(?:[\s>]|$)/

/** Apakah teks turn user ini buatan harness/webterm, bukan ketikan pengguna? */
export function isInjectedTurn(text: string): boolean {
  const head = text.trimStart().slice(0, 256).toLowerCase()
  const tag = LEADING_TAG.exec(head)?.[1]
  if (tag && HARNESS_TAGS.has(tag)) return true
  return HARNESS_PREFIXES.some((p) => head.startsWith(p))
}

export function newParseState(agent: HistoryAgent, id: string): SessionParseState {
  return { agent, id, cwd: null, title: null, startedAt: null, endedAt: null, messageCount: 0 }
}

const asObj = (v: unknown): Record<string, unknown> | null =>
  v && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : null
const str = (v: unknown): string | null => (typeof v === 'string' && v.trim() ? v.trim() : null)

/** Teks dari `content` berbentuk string atau array blok (`text`/`input_text`/`output_text`). */
export function contentText(content: unknown): string | null {
  if (typeof content === 'string') return str(content)
  if (!Array.isArray(content)) return null
  const parts: string[] = []
  for (const block of content) {
    const b = asObj(block)
    if (b && (b.type === 'text' || b.type === 'input_text' || b.type === 'output_text') && typeof b.text === 'string') {
      parts.push(b.text)
    }
  }
  return str(parts.join('\n'))
}

function toTitle(text: string | null): string | null {
  if (!text || isInjectedTurn(text)) return null
  const flat = text.replace(/\s+/g, ' ').trim()
  return flat ? flat.slice(0, TITLE_MAX) : null
}

function stamp(state: SessionParseState, ts: unknown): void {
  const t = typeof ts === 'string' ? Date.parse(ts) : NaN
  if (Number.isNaN(t)) return
  if (state.startedAt === null || t < state.startedAt) state.startedAt = t
  if (state.endedAt === null || t > state.endedAt) state.endedAt = t
}

function consumeClaude(s: SessionParseState, r: Record<string, unknown>): void {
  if (!s.cwd) s.cwd = str(r.cwd)
  if (r.type !== 'user' && r.type !== 'assistant') return
  s.messageCount++
  if (r.type === 'user' && !s.title && r.isMeta !== true) s.title = toTitle(contentText(asObj(r.message)?.content))
}

function consumeCodex(s: SessionParseState, r: Record<string, unknown>): void {
  const p = asObj(r.payload)
  if (!p) return
  if (r.type === 'session_meta') {
    s.id = str(p.id) ?? s.id
    s.cwd = s.cwd ?? str(p.cwd)
    return
  }
  if (r.type === 'turn_context') {
    s.cwd = s.cwd ?? str(p.cwd)
    return
  }
  // Codex menulis tiap turn DUA kali (response_item + event_msg). Yang dihitung hanya
  // response_item supaya jumlah pesan tidak berlipat; judul boleh dari keduanya.
  if (r.type === 'response_item' && p.type === 'message' && (p.role === 'user' || p.role === 'assistant')) {
    s.messageCount++
    if (p.role === 'user' && !s.title) s.title = toTitle(contentText(p.content))
    return
  }
  if (r.type === 'event_msg' && p.type === 'user_message' && !s.title) s.title = toTitle(str(p.message))
}

/** Satu baris JSONL ke state. Baris rusak (mis. potongan tulis yang belum selesai) dilewati. */
export function consumeLine(state: SessionParseState, line: string): void {
  if (!line.trim()) return
  let rec: Record<string, unknown> | null
  try {
    rec = asObj(JSON.parse(line))
  } catch {
    return // baris bukan JSON utuh: transcript lain tetap terindeks, baris ini memang tak bermakna
  }
  if (!rec) return
  if (state.agent === 'claude' && !str(state.id)) state.id = str(rec.sessionId) ?? state.id
  stamp(state, rec.timestamp)
  if (state.agent === 'claude') consumeClaude(state, rec)
  else consumeCodex(state, rec)
}

/** Id sesi dari nama file: Claude `<uuid>.jsonl`; Codex `rollout-<ts>-<uuid>.jsonl`. */
export function sessionIdFromFile(agent: HistoryAgent, fileName: string): string {
  const base = fileName.replace(/\.jsonl$/, '')
  if (agent === 'codex') {
    const m = /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$/i.exec(base)
    return m ? m[1] : base
  }
  return base
}
