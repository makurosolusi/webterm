import { describe, expect, it } from 'bun:test'
import type { Ca2Handle } from '../ca2Boot'
import { healthDispatch } from '../ca2Routes.health'
import { freshDb, rows, T0 } from '../guard/controlGuard.testutil'
import { dismissalKey } from './healthMemory'
import { createHealthStore } from './healthStore'

const B = '/api/central/health/findings'

function rig() {
  const db = freshDb()
  const store = createHealthStore(db, () => T0)
  const s = store.startScan('p1', 'scan')
  const [f] = store.finishScan(s.id, {
    drafts: [{ rule: 'empty_catch', severity: 'low', confidence: 'high', file: 'src/a.ts', line: 7, title: 'Empty catch', evidence: 'catch {}', source: 'Rule 11', suggestion: 'log it', fingerprint: 'fp' }],
    rules: ['empty_catch'], filesScanned: 1, truncated: false,
  }).opened
  const h = { db, now: () => T0 } as unknown as Ca2Handle
  const call = (verb: string, body: unknown = {}) => healthDispatch(h, { method: 'POST', path: `${B}/${f!.id}/${verb}`, query: new URLSearchParams(), body: async () => body }, 'human:root')
  const memories = () => rows(db, `SELECT key, title, body, status, kind, trust, source_kind, source_ref FROM memory WHERE source_kind = 'central_finding' ORDER BY created_at, rowid`)
  return { db, id: f!.id, call, memories }
}

describe('dismissal memory', () => {
  it('a dismiss writes one attested project fact; reopen supersedes it; a new dismiss writes a fresh one', async () => {
    const r = rig()
    expect((await r.call('dismiss', { reason: 'generated by protoc' })).status).toBe(200)
    expect(r.memories()).toEqual([{
      key: dismissalKey(r.id), title: 'Dismissed health finding: Empty catch', status: 'fact', kind: 'decision', trust: 'attested',
      body: "The user dismissed health finding 'Empty catch' (empty_catch, src/a.ts:7) on 2026-11-03: generated by protoc",
      source_kind: 'central_finding', source_ref: r.id,
    }])
    expect((await r.call('reopen')).status).toBe(200)
    expect(r.memories().map((m) => m['status'])).toEqual(['superseded'])
    expect((await r.call('dismiss', { reason: 'generated by protoc' })).status).toBe(200)
    const [old, fresh] = r.memories()
    expect(old).toMatchObject({ status: 'superseded' })
    expect(String(old!['key']).startsWith(`${dismissalKey(r.id)}#superseded:`)).toBe(true)
    expect(fresh).toMatchObject({ status: 'fact', key: dismissalKey(r.id) })
  })

  it('a failing memory write never fails the dismiss or the reopen', async () => {
    const r = rig()
    r.db.exec(`CREATE TRIGGER no_memory BEFORE INSERT ON memory BEGIN SELECT RAISE(ABORT, 'memory offline'); END`) // test-only failure
    expect(await r.call('dismiss', { reason: 'vendored' })).toMatchObject({ status: 200, body: { status: 'dismissed' } })
    expect(r.memories()).toEqual([])
    expect(await r.call('reopen')).toMatchObject({ status: 200, body: { status: 'open' } })
  })
})
