// The link catcher: `webterm-open` (the BROWSER handler) plus shims named like the programs that open a link
// (`open`, `xdg-open`, ...), installed into `<dataDir>/bin`, which every terminal session puts first on PATH.
// POSIX sh + curl like the `webterm` CLI. A shim ONLY takes web URLs (http/https/ftp); `file:` URLs and web-like files
// (.html/.htm/.xhtml/.svg) are refused (they would open the machine browser); every other call (folders, other files,
// `open -a App`, mailto:, no webterm credentials, switch off) goes to the real opener found on PATH AFTER
// the shim directory, with WEBTERM_OPEN_BYPASS set so nothing can loop back into a shim.
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { cliPath, shQuote } from '../cli/cli.launcher'
import { ESC_FN } from '../cli/cli.commands'
import { NODE_HEADERS_ENV } from '../hooksPaths'
import { LINK_BYPASS_ENV, LINK_HEADERS_ENV, LINK_OPEN_PATH, OPENER_SHIMS, OPEN_COMMAND } from './linkCapture.config'
import { shellDir, shellIntegrationFiles } from './linkCapture.shell'
import { DEFAULT_PORT } from '../serverConfig'

/** Marker in every generated file: the real-opener search skips anything that carries it (never exec a shim). */
export const SHIM_MARKER = 'webterm-open shim'

/** `<dataDir>/bin`: where the CLI and the shims live. */
export const shimDir = (): string => dirname(cliPath())
/** Absolute path of the BROWSER handler. */
export const openCommandPath = (): string => join(shimDir(), OPEN_COMMAND)

/** The catcher itself; `--webterm-as <name>` (first two args, set by a named shim) says which opener it stands in for. */
export function buildOpenCommand(): string {
  return `#!/bin/sh
# ${SHIM_MARKER} (generated by webterm on start - do not edit). Opens http(s) links in the canvas browser.
WT_BIN=${shQuote(shimDir())}
as=""
if [ "$1" = --webterm-as ]; then as="$2"; shift 2; fi
${ESC_FN}
# The real opener: first executable of that name on PATH that is not one of our shims.
real() {
  name="$as"
  if [ -z "$name" ]; then if [ "$(uname)" = Darwin ]; then name=open; else name=xdg-open; fi; fi
  export ${LINK_BYPASS_ENV}=1
  oldifs=$IFS; IFS=:
  for d in $PATH; do
    c="$d/$name"
    if [ -n "$d" ] && [ "$d" != "$WT_BIN" ] && [ -f "$c" ] && [ -x "$c" ] && ! head -c 256 "$c" 2>/dev/null | grep -q '${SHIM_MARKER}'; then IFS=$oldifs; exec "$c" "$@"; fi
  done
  IFS=$oldifs
  for c in "/usr/bin/$name" "/bin/$name" "/usr/local/bin/$name"; do
    if [ -x "$c" ]; then exec "$c" "$@"; fi
  done
  echo "webterm: no $name found to open: $*" >&2; exit 127
}
fail() { echo "webterm: could not open in canvas browser: $1; URL: $2" >&2; exit 1; }
isurl() { case "$1" in [hH][tT][tT][pP]://*|[hH][tT][tT][pP][sS]://*|[fF][tT][pP]://*) return 0 ;; *) return 1 ;; esac; }
# A file: URL or a web-like file (.html/.htm/.xhtml/.svg) would open in the machine browser: refused, never forwarded.
webfile() {
  case "$1" in [fF][iI][lL][eE]:*) return 0 ;; esac
  case "$(printf '%s' "$1" | tr 'A-Z' 'a-z')" in *.html|*.htm|*.xhtml|*.svg) return 0 ;; esac
  return 1
}
refuse() { echo "webterm: refused to open $1: web pages open in the canvas browser only. Serve it over http(s) and open that URL, or use 'Open in system browser' in the UI." >&2; exit 1; }
[ -z "\${${LINK_BYPASS_ENV}:-}" ] || real "$@"
[ "$#" -gt 0 ] || real "$@"
# An explicit app/reveal/editor flag (-a -b -R -e -t -f) is the user's own choice of program; otherwise the default handler of a web file is a browser.
explicit=""
if [ -n "$as" ]; then for a in "$@"; do case "$a" in -a|-b|-R|-e|-t|-f) explicit=1 ;; esac; done; fi
if [ -z "$explicit" ]; then for a in "$@"; do if webfile "$a"; then refuse "$a"; fi; done; fi
urls=""
if [ -n "$as" ]; then
  # A named opener takes over only when EVERY argument is an http(s) URL (a flag, file or app name = the user's own call).
  for a in "$@"; do isurl "$a" || real "$@"; done
  urls=1
else
  for a in "$@"; do if isurl "$a"; then urls=1; break; fi; done
  [ -n "$urls" ] || real "$@"
fi
hdr="\${${NODE_HEADERS_ENV}:-}"
if [ -z "$hdr" ] || [ ! -r "$hdr" ]; then hdr="\${${LINK_HEADERS_ENV}:-}"; fi
if [ -z "$hdr" ] || [ ! -r "$hdr" ]; then real "$@"; fi
API="http://127.0.0.1:\${WEBTERM_PORT:-${DEFAULT_PORT}}${LINK_OPEN_PATH}"
for u in "$@"; do
  isurl "$u" || continue
  resp=$(curl -sS --max-time 90 -H "@$hdr" -H 'content-type: application/json' --data-binary "{\\"url\\":\\"$(esc "$u")\\"}" -w '\\n%{http_code}' "$API" 2>/dev/null) || fail "the webterm server did not answer" "$u"
  code=$(printf '%s\\n' "$resp" | tail -n 1)
  body=$(printf '%s\\n' "$resp" | sed '$d')
  case "$code" in
    2*) case "$body" in *'"mode":"machine"'*) real "$@" ;; esac ;;
    *) msg=$(printf '%s' "$body" | sed -n 's/.*"message":"\\([^"]*\\)".*/\\1/p'); fail "\${msg:-HTTP $code}" "$u" ;;
  esac
done
exit 0
`
}

/** A shim named like an opener: it only hands over to `webterm-open` with its own name. */
export function buildOpenerShim(name: string): string {
  return `#!/bin/sh
# ${SHIM_MARKER} (generated by webterm on start - do not edit). Stands in for \`${name}\`.
exec ${shQuote(openCommandPath())} --webterm-as ${name} "$@"
`
}

/** Write the catcher, the named shims (0700) and the shell integration files; idempotent plain overwrite. */
export function installLinkCapture(): void {
  mkdirSync(shimDir(), { recursive: true, mode: 0o700 })
  const put = (file: string, body: string): void => { writeFileSync(file, body); chmodSync(file, 0o700) }
  put(openCommandPath(), buildOpenCommand())
  for (const name of OPENER_SHIMS) put(join(shimDir(), name), buildOpenerShim(name))
  mkdirSync(shellDir(), { recursive: true, mode: 0o700 })
  for (const [file, body] of Object.entries(shellIntegrationFiles())) writeFileSync(join(shellDir(), file), body, { mode: 0o600 })
}
