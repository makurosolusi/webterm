// The `webterm` CLI for agent sessions (plan F2-b), imitating Orca's CLI: a thin client over one
// registry. Orca references: discovery `src/cli/agent-context.ts:27-52`; the skill STUB
// (`skill-stubs/orca-cli.md:3-11`) only says "run `ORCA skills get orca-cli`", and `skills get`
// (`src/cli/handlers/skill-guide-get.ts:138-175`) prints the guide bundled with the executable, so the
// guide always matches the version that installed it. Here the guides are files written next to the
// launcher on every boot, and `skills get` reads them without contacting the server.
//
// POSIX sh + curl, like the shims it replaces: it carries NO token; curl reads the node's own header
// file (`-H @file`, path in WEBTERM_NODE_HEADERS), so the token is never in argv or in the env.
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { dataDir } from '../config'
import { flagOn } from '../envFlag'
import { NODE_HEADERS_ENV } from '../hooksPaths'
import { BROWSER_COMMAND, CONTEXT_COMMAND, ESC_FN } from './cli.commands'
import { buildEvalCommand } from './cli.eval'
import { SKILLS_COMMAND } from './cli.skills'
import { snapshotOf, TOOL_INDEX } from './cli.registry'
import { AGENT_REPORT_CAPABILITY } from '../capability/report.capabilities'

export const CLI_NAME = 'webterm'
/** Skill stub directory + front-matter `name`, and the guide `skills get` serves for it. */
export const CLI_SKILL_NAME = 'webterm-cli'
export const TOOLS_PATH = '/api/tools'

/** `<dataDir>/bin/webterm`: the webterm-owned bin dir agents run the CLI from. */
export const cliPath = (): string => join(dataDir(), 'bin', CLI_NAME)
/** Version-matched guides served by `webterm skills get <name>`. */
export const cliSkillsDir = (): string => join(dataDir(), 'cli', 'skills')
/** whats-new state (seen versions, registry snapshots). */
export const cliStateDir = (): string => join(dataDir(), 'cli')

/** Single-quote for sh: safe for any path, including spaces and quotes. */
export const shQuote = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`

/** Writes one guide that `webterm skills get <name>` serves (0600; the dir is created as needed). */
export function writeCliGuide(name: string, markdown: string): void {
  mkdirSync(cliSkillsDir(), { recursive: true, mode: 0o700 })
  writeFileSync(join(cliSkillsDir(), `${name}.md`), markdown, { mode: 0o600 })
}

/** The launcher script. Only builtins run before dispatch, so a PATH holding just `curl` is enough. */
export function buildWebtermCli(): string {
  return `#!/bin/sh
# webterm CLI (generated by webterm on start - do not edit). Thin client: the server decides everything.
SKILLS_DIR=${shQuote(cliSkillsDir())}
API_PATH='${TOOLS_PATH}'
die() { echo "$1" >&2; exit 2; }
${ESC_FN}
session() {
  hdr="\${${NODE_HEADERS_ENV}:-}"
  if [ -z "$hdr" ] || [ ! -r "$hdr" ]; then die "Not a webterm agent session (no node credentials)."; fi
  # legacy: NODETERM_PORT fallback for sessions started before the rename; remove after 0.10.0.
  API="http://127.0.0.1:\${WEBTERM_PORT:-\${NODETERM_PORT:-8700}}$API_PATH"
}
# Prints the response body; exit 0 on 2xx, 1 otherwise (the body says why).
send() {
  resp=$(curl -sS -H "@$hdr" -w '\\n%{http_code}' "$@") || exit 1
  code=$(printf '%s\\n' "$resp" | tail -n 1)
  printf '%s\\n' "$resp" | sed '$d'
  case "$code" in 2*) exit 0 ;; *) exit 1 ;; esac
}
accept() { if [ "$json" = 1 ]; then echo 'accept: application/json'; else echo 'accept: text/plain'; fi; }
cmd_help() {
  cat <<'EOF'
usage: webterm <command> [args]
  agent-context [--json]          what you can do here: every capability, its input schema, tier, and
                                  whether policy allows you right now
  <capability> --json '{...}'     run a capability (e.g. git.diff); prints a receipt
               [--operation-id <id>]  replay-safe retry: same id + same call = same receipt
  whats-new [--since <v>] [--json]  capabilities added/removed/changed since the registry you last saw
  skills get <name> [--json]      a launcher guide (webterm-cli, ...) or an approved canvas skill
  skills list [name]              canvas skills the user attached to your node (skill nodes cabled to Skills) + your open drafts
                                  (a name adds its body)
  skills propose --name webterm-<slug> --title <text> --description <text> [--audience canvas] [--caps a,b] [--body-file <path>|-]
                                  PROPOSE a new canvas skill (body from a file or stdin); a human must approve it.
                                  Always a canvas skill: central skills (Central's own rules) are not yours to write
  skills edit <name> [--title <text>] [--description <text>] [--caps a,b] [--body-file <path>|-]
                                  PROPOSE a new version of an active skill (unset fields keep the active text)
  report "<text>" [--done|--blocked|--question|--progress]
                                  tell Central now where your work stands (default --progress);
                                  done/blocked/question move your task and wake Central
  browser <verb> [args]           drive the browser node wired to this node (alias: webterm-browser)
  browser open --profile <name>   open it on a browser profile (own logins); \`browser profiles\` lists the names
  context <verb> [--node X]       read a linked node's context (alias: context.sh)
  eval run [--model fake|real]    replay promoted eval cases (user rejections) against Central
EOF
}
${SKILLS_COMMAND}
cmd_call() {
  name="$1"; shift
  case "$name" in ""|.*|*[!a-z0-9_.]*) die "Unknown command: $name (run: webterm help)" ;; esac
  args='{}'; op=""
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --json) [ "$#" -ge 2 ] || die "--json needs a JSON object"; args="$2"; shift 2 ;;
      --operation-id) [ "$#" -ge 2 ] || die "--operation-id needs a value"; op="$2"; shift 2 ;;
      *) die "usage: webterm $name --json '{...}' [--operation-id <id>]" ;;
    esac
  done
  case "$op" in *[!A-Za-z0-9._:-]*) die "bad operation id" ;; esac
  session
  send -X POST -H 'content-type: application/json' --data-binary "$args" "$API/$name\${op:+?operationId=$op}"
}
cmd_report() {
  kind=progress; text=""
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --done) kind=done ;; --blocked) kind=blocked ;; --question) kind=question ;; --progress) kind=progress ;;
      -*) die "usage: webterm report \\"<text>\\" [--done|--blocked|--question|--progress]" ;;
      *) [ -z "$text" ] || die "pass the report as one quoted argument"; text="$1" ;;
    esac
    shift
  done
  [ -n "$text" ] || die "usage: webterm report \\"<text>\\" [--done|--blocked|--question|--progress]"
  session
  send -X POST -H 'content-type: application/json' --data-binary "{\\"kind\\":\\"$kind\\",\\"text\\":\\"$(esc "$text")\\"}" "$API/${AGENT_REPORT_CAPABILITY}"
}
${BROWSER_COMMAND}
${CONTEXT_COMMAND}
${buildEvalCommand()}
cmd="\${1:-help}"; [ "$#" -gt 0 ] && shift
json=0
case "$cmd" in
  help|-h|--help) cmd_help ;;
  agent-context)
    [ "$1" = --json ] && json=1
    session; send -H "$(accept)" "$API" ;;
  whats-new)
    since=""
    while [ "$#" -gt 0 ]; do
      case "$1" in --json) json=1; shift ;; --since) [ "$#" -ge 2 ] || die "--since needs a version"; since="$2"; shift 2 ;; *) die "usage: webterm whats-new [--since <version>] [--json]" ;; esac
    done
    case "$since" in *[!0-9a-f]*) die "bad version" ;; esac
    session; send -H "$(accept)" "$API/whats-new\${since:+?since=$since}" ;;
  skills) cmd_skills "$@" ;;
  report) cmd_report "$@" ;;
  browser) cmd_browser "$@" ;;
  context) cmd_context "$@" ;;
  eval) cmd_eval "$@" ;;
  *) cmd_call "$cmd" "$@" ;;
esac
`
}

/** Version of the generated guides: the registry content hash, so a registry change changes it. */
export const cliGuideVersion = (): string => snapshotOf().version

/** Full guide behind the stub, generated from the registry (`webterm skills get webterm-cli`). */
export function buildCliGuide(cli: string = cliPath()): string {
  const rows = TOOL_INDEX.list().map((c) => `- \`${c.name}\` (${c.tier}${c.destructive ? ', destructive' : ''}): ${c.summary}`)
  return `---
name: ${CLI_SKILL_NAME}
version: ${cliGuideVersion()}
---

<!-- Generated by webterm on start. Hand edits are overwritten the next time it boots. -->

# webterm CLI

\`\`\`sh
${cli} <command> [args]
\`\`\`

1. Start with \`${cli} agent-context --json\`. It lists every capability with its input schema, tier,
   and \`allowed\`: whether policy lets THIS session run it right now. Do not call one that says
   \`allowed: false\`; ask your user instead. Only the user can change a rule.
2. Run one: \`${cli} <name> --json '{"key":"value"}'\`. The reply is \`{receipt, data}\`. \`receipt.outcome\`
   is \`ok\`, \`denied\` (policy said no: do not retry) or \`error\` (\`receipt.detail\` is a stable code).
3. Retrying something that may have run? Pass \`--operation-id <id>\`: the same id and the same call
   replay the first receipt instead of running twice.
4. \`${cli} whats-new\` shows what changed since the registry you last saw.
5. Report to Central any time: \`${cli} report "<text>" --done\` (your result), \`--blocked\`, \`--question\`, or
   \`--progress\` (the default). done/blocked/question move your task and wake Central at once; progress is recorded.
6. Skills: there are two kinds, never shared: \`central\` (rules for Central itself; you never see them) and \`canvas\` (reusable
   procedures for agents like you). \`${cli} skills list\` shows the canvas skills the user attached to your node (a skill node cabled to your Skills port) and
   \`${cli} skills get <name>\` prints one; follow the ones that apply to your task. \`${cli} skills propose --name webterm-<slug> --title "..." --description "..." --body-file <path|->\`
   proposes a new skill and \`${cli} skills edit <name> --body-file <path|->\` a new version of an existing one. You can only
   propose: a human approves it in webterm, and only then does it become active. A title is required (3-80 chars, one line, no markdown). Bodies are plain instructions (max 4000 chars) with the sections
   ## Purpose, ## When to use, ## Steps (numbered, at least 2), ## Do not, ## Done when (optional ## Notes); no URLs, shell commands or
   secrets. Lint rejects a thin skill and names only the issue code (\`structure:missing ## Steps\`).

Capabilities in this version:
${rows.join('\n')}

Also: \`${cli} browser <verb>\` (skill \`webterm-browser\`) and \`${cli} context <verb>\`
(skill \`webterm-linked-context\`). \`${cli} skills get <name>\` prints any of these guides.
MCP Apps: when a tool you call declares \`_meta.ui.resourceUri\` (a \`ui://\` view), read that resource and pass it to the webterm MCP tool \`app_open\` (\`{uri, html}\` or \`{resource}\`, plus \`toolInput\`/\`toolResult\`) to show it as an App node next to you.
`
}

/** Skill stub (Orca `skill-stubs/orca-cli.md`): it only points at the version-matched guide. */
export function buildCliSkillStub(cli: string = cliPath()): string {
  return `---
name: ${CLI_SKILL_NAME}
description: Discover and run what this webterm session may do (capabilities, policy, receipts) through the \`webterm\` CLI. Use when a task touches webterm nodes, approvals, git diffs or the canvas, or you need to know which webterm actions are allowed here.
---

<!-- Generated by webterm on start. Hand edits are overwritten the next time it boots. -->

# webterm CLI

This stub loads the version-matched guide from the webterm executable of this session.
Load it before running webterm commands; do not guess commands or flags:

\`\`\`sh
${cli} skills get ${CLI_SKILL_NAME}
\`\`\`
`
}

/** Set by `dev:fresh` (it shares the real HOME): the ~/.claude/skills files embed this instance's
 *  data-dir paths, so a second instance writing them would repoint the main install's skills at a temp dir. */
export const SKIP_HOME_INSTALLS_ENV = 'WEBTERM_SKIP_HOME_INSTALLS'
/** True when this instance must not write into HOME (only its own data dir). */
export const skipHomeInstalls = (env: NodeJS.ProcessEnv = process.env): boolean => flagOn(env[SKIP_HOME_INSTALLS_ENV])

/** Write the launcher (0700), its guide, and the stub skill. Idempotent plain overwrite; `home` for tests. */
export function installWebtermCli(home: string = homedir()): void {
  const file = cliPath()
  mkdirSync(join(dataDir(), 'bin'), { recursive: true, mode: 0o700 })
  writeFileSync(file, buildWebtermCli())
  chmodSync(file, 0o700)
  writeCliGuide(CLI_SKILL_NAME, buildCliGuide(file))
  if (skipHomeInstalls()) return
  const skillDir = join(home, '.claude', 'skills', CLI_SKILL_NAME)
  mkdirSync(skillDir, { recursive: true })
  writeFileSync(join(skillDir, 'SKILL.md'), buildCliSkillStub(file))
}
